//! Theme → Clink Lua scripts (spec §3.6): `init.lua` loads Oh My Posh and
//! `banner.lua` prints the welcome box. Every string goes through `lua_str`.
//!
//! Clink loads every script in its folder whenever it runs, `clink set` included (spec §2.2
//! #4), so neither script may do anything at load that a person would notice. `banner.lua`
//! only registers a callback for `clink.oninject`; everything else, the terminal check for
//! the icon and the reading of the variables included, happens when that callback runs.
//!
//! Everything CMD Studio writes into a cmd window is English, whatever the language of Windows
//! (spec §3.6): the date, the tips. Thai is for the app's own UI only.
use crate::color::Rgb;
use crate::model::Theme;
use crate::text::{lua_str, sanitize_text};
use std::path::Path;

const HEADER: &str = "-- Generated by CMD Studio. Do not edit: changes are overwritten.\n";

const INIT_BODY: &str = r#"-- cmd /c drops the outermost quotes, so the command is wrapped once more (spec gate G17).
-- 2>nul sits inside them: io.popen pipes stdout only, so without it the error text of cmd
-- (a missing exe) would be printed in every window.
local handle = io.popen('"' .. '"' .. omp .. '" init cmd --config "' .. config .. '" 2>nul' .. '"')
local script = handle and handle:read("*a") or ""
if handle then handle:close() end
if script == "" then
  log.info("cmdstudio: oh-my-posh init returned nothing")
  return
end
local chunk, err = load(script)
if not chunk then
  log.info("cmdstudio: cannot load oh-my-posh init: " .. tostring(err))
  return
end
-- A script that parses but raises must not print an error in every window either.
local ok, failure = pcall(chunk)
if not ok then
  log.info("cmdstudio: oh-my-posh init failed: " .. tostring(failure))
  return
end
log.info("cmdstudio: prompt loaded")
"#;

/// The `{date}` format (spec §3.6): the names of the days and the months, how the day of the
/// month is written, and the year. The generator embeds these itself and never takes a name
/// from `os.date`: on Windows that follows the language of the machine (Thai Windows gives
/// Thai names), and what CMD Studio writes into cmd is English. The preview emulator writes
/// the date from the same tables ([`DateStyle::format`]), and `tests/banner_parity.rs` holds
/// the two to each other for every day of a year.
pub(crate) struct DateStyle {
    /// Sunday first, the way Lua's `os.date("*t").wday` counts.
    days: [&'static str; 7],
    months: [&'static str; 12],
    /// Whether the day of the month always has two digits (`09`). The Lua pattern and the
    /// Rust text are both made from this, so they cannot say different things.
    pad_day: bool,
    /// Added to the year of `os.date("*t")`: 0, so the year is the Gregorian one.
    year_offset: u32,
}

impl DateStyle {
    /// The `string.format` pattern banner.lua uses: the day name, the day, the month name
    /// and the year.
    fn pattern(&self) -> &'static str {
        if self.pad_day {
            "%s %02d %s %d"
        } else {
            "%s %d %s %d"
        }
    }

    /// The date as banner.lua's `today()` writes it. `wday` counts from 1 for Sunday, as
    /// `os.date("*t")` does; `month` from 1 for January. A day of the week or a month out of
    /// range (which `os.date` never gives, but the preview's clock comes from the app) is
    /// named `?`; the day of the month and the year are written as the numbers they are.
    pub(crate) fn format(&self, wday: u8, day: u8, month: u8, year: u16) -> String {
        let name = |list: &[&'static str], number: u8| {
            usize::from(number)
                .checked_sub(1)
                .and_then(|i| list.get(i))
                .copied()
                .unwrap_or("?")
        };
        let year = u32::from(year).saturating_add(self.year_offset);
        let (day_name, month_name) = (name(&self.days, wday), name(&self.months, month));
        if self.pad_day {
            format!("{day_name} {day:02} {month_name} {year}")
        } else {
            format!("{day_name} {day} {month_name} {year}")
        }
    }
}

/// `Fri 09 Oct 2026`: the one style, on every Windows.
pub(crate) const DATE_EN: DateStyle = DateStyle {
    days: ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"],
    months: [
        "Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec",
    ],
    pad_day: true,
    year_offset: 0,
};

/// The Lua behind the banner variables. It reads the `DAYS`, `MONTHS`, `DATE_FORMAT` and
/// `YEAR_OFFSET` that [`vars_lua`] puts in front of it. The only things it asks `os.date` for
/// are numbers and the digits of `%H:%M`.
///
/// The user name, the computer name and the folder are read when the box is printed, and
/// nobody has cleaned them: a folder can be named with U+202E or a C1 control, and `{cwd}` is
/// the folder cmd was opened in. `clean` drops what could drive the terminal or reorder the
/// text after it: C0 controls and DEL, C1 controls (UTF-8 C2 80 to C2 9F), U+2028 and U+2029,
/// and the bidirectional embeddings, overrides and isolates U+202A to U+202E and U+2066 to
/// U+2069. That is the set `sanitize_text` drops from the text of a theme, except that
/// `sanitize_text` takes a whole escape sequence: here the escape character goes and the
/// rest of the sequence stays as plain text. Each pattern starts at a lead byte, or at a
/// byte (C0, DEL) that never occurs inside a multi-byte character, so on UTF-8 none of them
/// can match in the middle of another character. The first class names NUL as `\0`: Lua 5.2,
/// which Clink runs, takes it in a pattern, and has deprecated the `%z` of Lua 5.1.
const VARS_BODY: &str = r#"local function clean(s)
  s = s:gsub("[\0\1-\31\127]", "")
  s = s:gsub("\194[\128-\159]", "")
  s = s:gsub("\226\128[\168-\174]", "")
  s = s:gsub("\226\129[\166-\169]", "")
  return s
end
local function today()
  local t = os.date("*t")
  return string.format(DATE_FORMAT, DAYS[t.wday], t.day, MONTHS[t.month], t.year + YEAR_OFFSET)
end
local V = {
  user = function() return clean(os.getenv("USERNAME") or "") end,
  host = function() return clean(os.getenv("COMPUTERNAME") or "") end,
  cwd = function() return clean(os.getcwd() or "") end,
  date = today,
  time = function() return os.date("%H:%M") end,
}
"#;

/// The tips line under the box, English on every Windows (spec §3.6).
pub(crate) const TIPS_EN: &str =
    " Tips: help for commands \u{b7} cls to clear \u{b7} \u{2191} for history";

/// The icon of the box where the terminal can draw it. Windows Terminal sets `WT_SESSION` in
/// every tab and falls back to another font for a glyph its font lacks. conhost has no
/// fallback: on Windows 10 with its default font it draws U+273B as an empty box (spec §3.6).
/// The check is the variable and nothing more, so a conhost window started from a Windows
/// Terminal tab inherits it and gets the glyph too.
pub(crate) const ICON: &str = "\u{273b}";
/// The icon everywhere else: an asterisk, which every font has, one cell wide like the star.
pub(crate) const ICON_FALLBACK: &str = "*";

const PRINT_FN: &str = r#"local function print_banner()
  local lines = build()
  local width = 0
  for _, l in ipairs(lines) do
    width = math.max(width, console.cellcount(l))
  end
  width = width + 2
  local out = { ACCENT .. "╭" .. string.rep("─", width + 2) .. "╮" .. RESET }
  for _, l in ipairs(lines) do
    local pad = string.rep(" ", width - console.cellcount(l))
    out[#out + 1] = ACCENT .. "│" .. RESET .. " " .. l .. pad .. " " .. ACCENT .. "│" .. RESET
  end
  out[#out + 1] = ACCENT .. "╰" .. string.rep("─", width + 2) .. "╯" .. RESET
  if TIPS then out[#out + 1] = MUTED .. TIPS .. RESET end
  -- One space, never an empty line: an empty last line broke the first
  -- collapsed prompt in the prototype (spec 2.2 #3).
  out[#out + 1] = " "
  clink.print(table.concat(out, "\n"))
end
"#;

const CLEAR_LOGO_FN: &str = r#"local function clear_cmd_logo()
  local l1 = console.getlinetext(1) or ""
  local l2 = console.getlinetext(2) or ""
  if l1:find("^Microsoft Windows %[") and l2:find("^%(c%) Microsoft Corporation") then
    clink.print("\027[2J\027[3J\027[H", NONL)
  end
end
"#;

/// The start of the callback. `CMDSTUDIO_BANNER` is inherited by every cmd started from
/// this one, so a nested window does not print the box again (spec §3.6).
const ON_INJECT_HEAD: &str = r#"clink.oninject(function()
  if os.getenv("CMDSTUDIO_BANNER") then return end
  os.setenv("CMDSTUDIO_BANNER", "1")
"#;

/// The SGR sequence that ends a color.
const RESET_SGR: &str = "\u{1b}[0m";

/// The SGR sequence for a 24-bit foreground color.
fn sgr(c: Rgb) -> String {
    format!("\u{1b}[38;2;{};{};{}m", c.r, c.g, c.b)
}

/// A Lua table of strings, each written by `lua_str`: `{ "a", "b" }`.
fn lua_list(items: &[&str]) -> String {
    let quoted: Vec<String> = items.iter().map(|item| lua_str(item)).collect();
    format!("{{ {} }}", quoted.join(", "))
}

/// The Lua that defines the banner variables `V.user()`, `V.host()`, `V.cwd()`, `V.date()`
/// and `V.time()`: the names of the days and months, the pattern of the date and the offset of
/// the year, then the block that uses them (spec §3.6).
fn vars_lua() -> String {
    let style = &DATE_EN;
    format!(
        "local DAYS = {}\nlocal MONTHS = {}\nlocal DATE_FORMAT = {}\nlocal YEAR_OFFSET = {}\n{VARS_BODY}",
        lua_list(&style.days),
        lua_list(&style.months),
        lua_str(style.pattern()),
        style.year_offset,
    )
}

/// The function that gives the icon of the box, chosen when the box is printed and not when
/// the script loads.
fn icon_lua() -> String {
    format!(
        "local function icon()\n  if os.getenv(\"WT_SESSION\") then return {} end\n  return {}\nend\n",
        lua_str(ICON),
        lua_str(ICON_FALLBACK)
    )
}

/// A banner variable (spec §3.3).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum Var {
    User,
    Host,
    Cwd,
    Date,
    Time,
}

impl Var {
    /// The Lua call that stands for the variable in banner.lua.
    fn call(self) -> &'static str {
        match self {
            Var::User => "V.user()",
            Var::Host => "V.host()",
            Var::Cwd => "V.cwd()",
            Var::Date => "V.date()",
            Var::Time => "V.time()",
        }
    }
}

/// The banner variables as a template writes them. They are lower case and keep their
/// braces; any other `{word}` is text.
const VARS: [(&str, Var); 5] = [
    ("{user}", Var::User),
    ("{host}", Var::Host),
    ("{cwd}", Var::Cwd),
    ("{date}", Var::Date),
    ("{time}", Var::Time),
];

/// A piece of a banner template: text, or a variable.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum Piece<'a> {
    Text(&'a str),
    Var(Var),
}

/// The first variable in `text`: the text before it, the variable and the text after it.
fn next_variable(text: &str) -> Option<(&str, Var, &str)> {
    text.match_indices('{').find_map(|(at, _)| {
        let (before, from) = text.split_at_checked(at)?;
        VARS.iter()
            .find_map(|(name, var)| from.strip_prefix(*name).map(|after| (before, *var, after)))
    })
}

/// A banner template cut into text and variables, from left to right. The text a variable
/// stands for is never read again, so a user named `{host}` stays `{host}`. banner.lua and
/// the preview both cut templates here.
pub(crate) fn template_pieces(template: &str) -> Vec<Piece<'_>> {
    let mut pieces = Vec::new();
    let mut rest = template;
    while let Some((before, var, after)) = next_variable(rest) {
        if !before.is_empty() {
            pieces.push(Piece::Text(before));
        }
        pieces.push(Piece::Var(var));
        rest = after;
    }
    if !rest.is_empty() {
        pieces.push(Piece::Text(rest));
    }
    pieces
}

/// A banner template as a Lua expression. Known `{variables}` become calls;
/// everything else stays literal (spec §3.3), written by `lua_str`.
pub(crate) fn template_expr(template: &str) -> String {
    let parts: Vec<String> = template_pieces(template)
        .into_iter()
        .map(|piece| match piece {
            Piece::Text(text) => lua_str(text),
            Piece::Var(var) => var.call().to_string(),
        })
        .collect();
    if parts.is_empty() {
        lua_str("")
    } else {
        parts.join(" .. ")
    }
}

/// `init.lua`: runs Oh My Posh by its full path, so nothing depends on PATH, and loads what
/// it prints. `io.popen` hands the command to `cmd /c`, which drops the outermost quotes,
/// so the command is `""<exe>" init cmd --config "<config>" 2>nul"` (spec §5.4, G17). The
/// `2>nul` keeps the error text of cmd (a missing exe) out of every window, because
/// `io.popen` pipes stdout only. The script runs in every cmd window, so it never raises
/// and never prints: a failure is logged. Both paths are written by `lua_str`, which keeps
/// Thai letters, spaces, `\` and `]]` as they are. A path that is not valid Unicode is
/// written with U+FFFD in place of the parts that are not.
pub fn init_lua(omp_exe: &Path, omp_config: &Path) -> String {
    let mut s = String::from(HEADER);
    s.push_str(&format!(
        "local omp = {}\n",
        lua_str(&omp_exe.to_string_lossy())
    ));
    s.push_str(&format!(
        "local config = {}\n",
        lua_str(&omp_config.to_string_lossy())
    ));
    s.push_str(INIT_BODY);
    s
}

/// `banner.lua`: the welcome box of the theme (spec §3.6). Loading it registers one
/// `clink.oninject` callback and prints nothing; the callback prints the box once per
/// session, guarded by the environment variable `CMDSTUDIO_BANNER`. A theme with the banner
/// turned off gets a script that registers nothing, so an older banner is replaced by it.
///
/// The texts of the theme go through `sanitize_text` and then `lua_str`. Import has cleaned
/// them already, but a theme built in code has not been through that, and an escape
/// sequence in the title would otherwise reach the terminal. The user name, the computer
/// name and the folder are not in the theme: the script reads them when it prints and
/// cleans them itself (see `VARS_BODY`).
///
/// What the script itself says, the date and the tips, is English on every Windows; the
/// theme's own texts and the variables are shown as they are.
pub fn banner_lua(theme: &Theme) -> String {
    let b = &theme.banner;
    let mut s = String::from(HEADER);
    if !b.enabled {
        s.push_str("-- The banner is turned off in this theme.\n");
        return s;
    }
    s.push_str(&format!(
        "local ACCENT = {}\n",
        lua_str(&sgr(theme.colors.accent))
    ));
    s.push_str(&format!(
        "local MUTED = {}\n",
        lua_str(&sgr(theme.colors.muted))
    ));
    s.push_str(&format!("local RESET = {}\n", lua_str(RESET_SGR)));
    s.push_str(&vars_lua());
    s.push_str(&icon_lua());
    s.push_str("local function build()\n  return {\n");
    s.push_str(&format!(
        "    ACCENT .. icon() .. RESET .. \" \" .. ({}),\n",
        template_expr(&sanitize_text(&b.title))
    ));
    if !b.lines.is_empty() {
        s.push_str("    \"\",\n");
        for line in &b.lines {
            s.push_str(&format!(
                "    MUTED .. \"  \" .. ({}) .. RESET,\n",
                template_expr(&sanitize_text(line))
            ));
        }
    }
    s.push_str("  }\nend\n");
    let tips = b.tips.then_some(TIPS_EN);
    s.push_str(&format!(
        "local TIPS = {}\n",
        tips.map_or_else(|| "nil".to_string(), lua_str)
    ));
    s.push_str(PRINT_FN);
    if b.clear_logo {
        s.push_str(CLEAR_LOGO_FN);
    }
    s.push_str(ON_INJECT_HEAD);
    if b.clear_logo {
        s.push_str("  clear_cmd_logo()\n");
    }
    s.push_str("  print_banner()\nend)\n");
    s
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::presets::terracotta;
    use std::path::Path;

    #[test]
    fn templates_become_lua_expressions() {
        assert_eq!(
            template_expr("Welcome back, {user}!"),
            "\"Welcome back, \" .. V.user() .. \"!\""
        );
        assert_eq!(
            template_expr("{date} · {time}"),
            "V.date() .. \" · \" .. V.time()"
        );
        assert_eq!(template_expr("{foo} stays"), "\"{foo} stays\"");
        assert_eq!(template_expr(""), "\"\"");
    }

    #[test]
    fn every_variable_is_a_call_and_only_those_five() {
        // spec §3.3: `{user} {host} {cwd} {date} {time}`, in lower case, braces and all
        for (word, call) in [
            ("user", "V.user()"),
            ("host", "V.host()"),
            ("cwd", "V.cwd()"),
            ("date", "V.date()"),
            ("time", "V.time()"),
        ] {
            assert_eq!(template_expr(&format!("{{{word}}}")), call);
        }
        for literal in [
            "{USER}", "{User}", "{ user }", "{user", "user}", "{}", "{", "}", "{{", "{path}",
            "{user }",
        ] {
            assert_eq!(template_expr(literal), lua_str(literal), "{literal:?}");
        }
    }

    #[test]
    fn variables_and_text_can_touch_each_other() {
        assert_eq!(template_expr("{user}{host}"), "V.user() .. V.host()");
        assert_eq!(
            template_expr("a{cwd}b{time}c"),
            "\"a\" .. V.cwd() .. \"b\" .. V.time() .. \"c\""
        );
        // a brace that opens nothing stays text, and the variable inside the second pair is found
        assert_eq!(template_expr("{{user}}"), "\"{\" .. V.user() .. \"}\"");
        assert_eq!(
            template_expr("{use{user}r}"),
            "\"{use\" .. V.user() .. \"r}\""
        );
        // the text on either side may be Thai or emoji: the cuts fall on character boundaries
        assert_eq!(
            template_expr("ก{user}ข 👋{date}"),
            "\"ก\" .. V.user() .. \"ข 👋\" .. V.date()"
        );
        assert_eq!(template_expr("{ก}"), "\"{ก}\"");
    }

    #[test]
    fn text_between_variables_is_escaped_by_lua_str() {
        // spec §3.7 #4: a quote, a backslash, a long-bracket close and a control character
        // are all text; none of them can end the string
        assert_eq!(template_expr("a\"]]\\"), "\"a\\\"]]\\\\\"");
        assert_eq!(
            template_expr("x\ny{user}\u{1b}[0m"),
            "\"x\\010y\" .. V.user() .. \"\\027[0m\""
        );
    }

    #[test]
    fn init_lua_quotes_paths_and_wraps_the_popen_command() {
        let s = init_lua(
            Path::new(r"C:\Users\ทดสอบ ผู้ใช้\omp.exe"),
            Path::new(r"C:\x\theme.omp.json"),
        );
        assert!(s.contains(r#"local omp = "C:\\Users\\ทดสอบ ผู้ใช้\\omp.exe""#));
        assert!(s.contains(r#"io.popen('"' .. '"' .. omp"#));
        // `2>nul` is inside the outer quotes, which cmd drops: io.popen pipes stdout only, so
        // without it cmd's own error text (a missing exe) would be printed in every window
        assert!(s.contains(
            r#"io.popen('"' .. '"' .. omp .. '" init cmd --config "' .. config .. '" 2>nul' .. '"')"#
        ));
    }

    #[test]
    fn init_lua_embeds_both_paths_only_through_lua_str() {
        // `]]` would close a long string, `\` and `"` would break a short one, and a path
        // is free to hold Thai letters and spaces. tests/banner_lua.rs runs the result.
        let exe = r"C:\Users\ทดสอบ ผู้ใช้\]]\--[[\omp.exe";
        let config = r"D:\a b\x]]\theme.omp.json";
        let s = init_lua(Path::new(exe), Path::new(config));
        assert!(s.contains(&format!("local omp = {}\n", lua_str(exe))));
        assert!(s.contains(&format!("local config = {}\n", lua_str(config))));
        assert!(s.starts_with(HEADER));
    }

    #[test]
    fn disabled_banner_registers_nothing() {
        // Review Focus 4
        let mut t = terracotta();
        t.banner.enabled = false;
        assert!(!banner_lua(&t).contains("oninject"));
    }

    #[test]
    fn templates_are_cut_into_text_and_variables() {
        assert_eq!(
            template_pieces("Hi {user}!"),
            [Piece::Text("Hi "), Piece::Var(Var::User), Piece::Text("!")]
        );
        assert_eq!(
            template_pieces("{{date}}{time}"),
            [
                Piece::Text("{"),
                Piece::Var(Var::Date),
                Piece::Text("}"),
                Piece::Var(Var::Time)
            ]
        );
        assert_eq!(
            template_pieces("{foo} {USER}"),
            [Piece::Text("{foo} {USER}")]
        );
        assert!(template_pieces("").is_empty());
    }

    #[test]
    fn the_date_is_written_the_same_in_rust_and_in_lua() {
        // spec §3.6: Friday 9 October 2026 is `Fri 09 Oct 2026` on every Windows, and the Lua
        // pattern says the same (the day padded to two digits, the Gregorian year)
        assert_eq!(DATE_EN.format(6, 9, 10, 2026), "Fri 09 Oct 2026");
        assert_eq!(DATE_EN.pattern(), "%s %02d %s %d");
        assert_eq!(
            DATE_EN.year_offset, 0,
            "no Buddhist era: the year is the calendar's"
        );
        // every name is English: ASCII, with no Thai character anywhere in the tables
        for name in DATE_EN.days.iter().chain(DATE_EN.months.iter()) {
            assert!(name.is_ascii(), "{name:?}");
        }
        assert!(!TIPS_EN
            .chars()
            .any(|c| ('\u{e00}'..='\u{e7f}').contains(&c)));
        // a day or month out of range is a question mark, not a panic
        assert_eq!(DATE_EN.format(0, 1, 13, 2026), "? 01 ? 2026");
    }

    #[test]
    fn a_date_out_of_range_is_written_and_never_panics() {
        // The preview's clock comes from the app and nothing checks it (Task 2's review). A
        // day of the week or a month out of range is named `?`; the day of the month and the
        // year are written as the numbers they are, as `string.format` would write them.
        assert_eq!(DATE_EN.format(0, 0, 0, 0), "? 00 ? 0");
        assert_eq!(DATE_EN.format(8, 32, 13, 2026), "? 32 ? 2026");
        assert_eq!(
            DATE_EN.format(u8::MAX, u8::MAX, u8::MAX, u16::MAX),
            "? 255 ? 65535"
        );
        assert_eq!(DATE_EN.format(7, 31, 12, u16::MAX), "Sat 31 Dec 65535");
        assert_eq!(DATE_EN.format(1, 1, 1, 0), "Sun 01 Jan 0");
        // every day of the week and every month a `u8` holds: a name from the tables exactly
        // when it is in range
        for wday in 0..=u8::MAX {
            for month in 0..=u8::MAX {
                let text = DATE_EN.format(wday, 9, month, 2026);
                let words: Vec<&str> = text.split(' ').collect();
                assert_eq!(words.len(), 4, "{text}");
                assert_eq!(words[0] == "?", !(1..=7).contains(&wday), "{text}");
                assert_eq!(words[1], "09", "{text}");
                assert_eq!(words[2] == "?", !(1..=12).contains(&month), "{text}");
                assert_eq!(words[3], "2026", "{text}");
            }
        }
    }
}
