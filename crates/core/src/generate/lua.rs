/// The `{date}` format (spec §3.6): the names of the days and the months, how the day of the
/// month is written, and the year. The generator embeds these itself and never takes a name
/// from `os.date`: on Windows that follows the language of the machine (Thai Windows gives
/// Thai names), and what CMD Studio writes into cmd is English. The preview emulator writes
/// the date from the same tables ([`DateStyle::format`]), and `tests/banner_parity.rs` holds
/// the two to each other for every day of a year.
pub(crate) struct DateStyle {
    /// Sunday first, the way Lua's `os.date("*t").wday` counts.
    days: [&'static str; 7],
    months: [&'static str; 12],
    /// Whether the day of the month always has two digits (`09`). The Lua pattern and the
    /// Rust text are both made from this, so they cannot say different things.
    pad_day: bool,
    /// Added to the year of `os.date("*t")`: 0, so the year is the Gregorian one.
    year_offset: u32,
}

impl DateStyle {
    /// The `string.format` pattern banner.lua uses: the day name, the day, the month name
    /// and the year.
    fn pattern(&self) -> &'static str {
        if self.pad_day {
            "%s %02d %s %d"
        } else {
            "%s %d %s %d"
        }
    }

    /// The date as banner.lua's `today()` writes it. `wday` counts from 1 for Sunday, as
    /// `os.date("*t")` does; `month` from 1 for January. A day of the week or a month out of
    /// range (which `os.date` never gives, but the preview's clock comes from the app) is
    /// named `?`; the day of the month and the year are written as the numbers they are.
    pub(crate) fn format(&self, wday: u8, day: u8, month: u8, year: u16) -> String {
        let name = |list: &[&'static str], number: u8| {
            usize::from(number)
                .checked_sub(1)
                .and_then(|i| list.get(i))
                .copied()
                .unwrap_or("?")
        };
        let year = u32::from(year).saturating_add(self.year_offset);
        let (day_name, month_name) = (name(&self.days, wday), name(&self.months, month));
        if self.pad_day {
            format!("{day_name} {day:02} {month_name} {year}")
        } else {
            format!("{day_name} {day} {month_name} {year}")
        }
    }
}

/// `Fri 09 Oct 2026`: the one style, on every Windows.
pub(crate) const DATE_EN: DateStyle = DateStyle {
    days: ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"],
    months: [
        "Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec",
    ],
    pad_day: true,
    year_offset: 0,
};

/// The Lua behind the banner variables. It reads the `DAYS`, `MONTHS`, `DATE_FORMAT` and
/// `YEAR_OFFSET` that [`vars_lua`] puts in front of it. The only things it asks `os.date` for
/// are numbers and the digits of `%H:%M`.
///
/// The user name, the computer name and the folder are read when the box is printed, and
/// nobody has cleaned them: a folder can be named with U+202E or a C1 control, and `{cwd}` is
/// the folder cmd was opened in. `clean` drops what could drive the terminal or reorder the
/// text after it: C0 controls and DEL, C1 controls (UTF-8 C2 80 to C2 9F), U+2028 and U+2029,
/// and the bidirectional embeddings, overrides and isolates U+202A to U+202E and U+2066 to
/// U+2069. That is the set `sanitize_text` drops from the text of a theme, except that
/// `sanitize_text` takes a whole escape sequence: here the escape character goes and the
/// rest of the sequence stays as plain text. Each pattern starts at a lead byte, or at a
/// byte (C0, DEL) that never occurs inside a multi-byte character, so on UTF-8 none of them
/// can match in the middle of another character. The first class names NUL as `\0`: Lua 5.2,
/// which Clink runs, takes it in a pattern, and has deprecated the `%z` of Lua 5.1.
const VARS_BODY: &str = r#"local function clean(s)
  s = s:gsub("[\0\1-\31\127]", "")
  s = s:gsub("\194[\128-\159]", "")
  s = s:gsub("\226\128[\168-\174]", "")
  s = s:gsub("\226\129[\166-\169]", "")
  return s
end
local function today()
  local t = os.date("*t")
  return string.format(DATE_FORMAT, DAYS[t.wday], t.day, MONTHS[t.month], t.year + YEAR_OFFSET)
end
local V = {
  user = function() return clean(os.getenv("USERNAME") or "") end,
  host = function() return clean(os.getenv("COMPUTERNAME") or "") end,
  cwd = function() return clean(os.getcwd() or "") end,
  date = today,
  time = function() return os.date("%H:%M") end,
}
"#;

