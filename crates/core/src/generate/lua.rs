//! Theme → Clink Lua scripts (spec §3.6): `init.lua` loads Oh My Posh and
//! `banner.lua` prints the welcome box. Every string goes through `lua_str`.
//!
//! Clink loads every script in its folder whenever it runs, `clink set` included (spec §2.2
//! #4), so neither script may do anything at load that a person would notice. `banner.lua`
//! only registers a callback for `clink.oninject`; everything else, the terminal check for
//! the icon and the reading of the variables included, happens when that callback runs.
use crate::color::Rgb;
use crate::model::Theme;
use crate::text::{lua_str, sanitize_text};
use std::path::Path;

/// Language of generated user-visible text (dates, tips).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Lang {
    /// Thai names, and the year in the Buddhist era: `ศ. 9 ต.ค. 2569`.
    Th,
    /// English names and the Gregorian year: `Fri 09 Oct 2026`.
    En,
}

const HEADER: &str = "-- Generated by CMD Studio. Do not edit: changes are overwritten.\n";

const INIT_BODY: &str = r#"-- cmd /c drops the outermost quotes, so the command is wrapped once more (spec gate G17).
-- 2>nul sits inside them: io.popen pipes stdout only, so without it the error text of cmd
-- (a missing exe) would be printed in every window.
local handle = io.popen('"' .. '"' .. omp .. '" init cmd --config "' .. config .. '" 2>nul' .. '"')
local script = handle and handle:read("*a") or ""
if handle then handle:close() end
if script == "" then
  log.info("cmdstudio: oh-my-posh init returned nothing")
  return
end
local chunk, err = load(script)
if not chunk then
  log.info("cmdstudio: cannot load oh-my-posh init: " .. tostring(err))
  return
end
-- A script that parses but raises must not print an error in every window either.
local ok, failure = pcall(chunk)
if not ok then
  log.info("cmdstudio: oh-my-posh init failed: " .. tostring(failure))
  return
end
log.info("cmdstudio: prompt loaded")
"#;

/// What differs between the two `{date}` formats (spec §3.6): the names of the days and the
/// months, how the day of the month is written, and the era of the year. The generator
/// embeds these itself and never takes a name from `os.date`: on Windows that follows the
/// language of the machine, which is not the language of the app.
struct DateStyle {
    /// Sunday first, the way Lua's `os.date("*t").wday` counts.
    days: [&'static str; 7],
    months: [&'static str; 12],
    /// A `string.format` pattern for the day name, the day, the month name and the year.
    pattern: &'static str,
    /// Added to the year of the Gregorian calendar; 543 gives the Buddhist era.
    year_offset: u32,
}

/// `ศ. 9 ต.ค. 2569`
const DATE_TH: DateStyle = DateStyle {
    days: ["อา.", "จ.", "อ.", "พ.", "พฤ.", "ศ.", "ส."],
    months: [
        "ม.ค.",
        "ก.พ.",
        "มี.ค.",
        "เม.ย.",
        "พ.ค.",
        "มิ.ย.",
        "ก.ค.",
        "ส.ค.",
        "ก.ย.",
        "ต.ค.",
        "พ.ย.",
        "ธ.ค.",
    ],
    pattern: "%s %d %s %d",
    year_offset: 543,
};

/// `Fri 09 Oct 2026`
const DATE_EN: DateStyle = DateStyle {
    days: ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"],
    months: [
        "Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec",
    ],
    pattern: "%s %02d %s %d",
    year_offset: 0,
};

/// The Lua behind the banner variables, the same for both languages. It reads the `DAYS`,
/// `MONTHS`, `DATE_FORMAT` and `YEAR_OFFSET` that [`vars_lua`] puts in front of it. The only
/// things it asks `os.date` for are numbers and the digits of `%H:%M`.
const VARS_BODY: &str = r#"local function today()
  local t = os.date("*t")
  return string.format(DATE_FORMAT, DAYS[t.wday], t.day, MONTHS[t.month], t.year + YEAR_OFFSET)
end
local V = {
  user = function() return os.getenv("USERNAME") or "" end,
  host = function() return os.getenv("COMPUTERNAME") or "" end,
  cwd = function() return os.getcwd() end,
  date = today,
  time = function() return os.date("%H:%M") end,
}
"#;

const TIPS_TH: &str = " ทิป: help ดูคำสั่ง \u{b7} cls ล้างจอ \u{b7} \u{2191} ดูประวัติ";
const TIPS_EN: &str = " Tips: help for commands \u{b7} cls to clear \u{b7} \u{2191} for history";

/// The icon of the box where the terminal can draw it. Windows Terminal sets `WT_SESSION` in
/// every tab and falls back to another font for a glyph its font lacks. conhost has no
/// fallback: on Windows 10 with its default font it draws U+273B as an empty box (spec §3.6).
/// The check is the variable and nothing more, so a conhost window started from a Windows
/// Terminal tab inherits it and gets the glyph too.
const ICON: &str = "\u{273b}";
/// The icon everywhere else: an asterisk, which every font has, one cell wide like the star.
const ICON_FALLBACK: &str = "*";

const PRINT_FN: &str = r#"local function print_banner()
  local lines = build()
  local width = 0
  for _, l in ipairs(lines) do
    width = math.max(width, console.cellcount(l))
  end
  width = width + 2
  local out = { ACCENT .. "╭" .. string.rep("─", width + 2) .. "╮" .. RESET }
  for _, l in ipairs(lines) do
    local pad = string.rep(" ", width - console.cellcount(l))
    out[#out + 1] = ACCENT .. "│" .. RESET .. " " .. l .. pad .. " " .. ACCENT .. "│" .. RESET
  end
  out[#out + 1] = ACCENT .. "╰" .. string.rep("─", width + 2) .. "╯" .. RESET
  if TIPS then out[#out + 1] = MUTED .. TIPS .. RESET end
  -- One space, never an empty line: an empty last line broke the first
  -- collapsed prompt in the prototype (spec 2.2 #3).
  out[#out + 1] = " "
  clink.print(table.concat(out, "\n"))
end
"#;

const CLEAR_LOGO_FN: &str = r#"local function clear_cmd_logo()
  local l1 = console.getlinetext(1) or ""
  local l2 = console.getlinetext(2) or ""
  if l1:find("^Microsoft Windows %[") and l2:find("^%(c%) Microsoft Corporation") then
    clink.print("\027[2J\027[3J\027[H", NONL)
  end
end
"#;

/// The start of the callback. `CMDSTUDIO_BANNER` is inherited by every cmd started from
/// this one, so a nested window does not print the box again (spec §3.6).
const ON_INJECT_HEAD: &str = r#"clink.oninject(function()
  if os.getenv("CMDSTUDIO_BANNER") then return end
  os.setenv("CMDSTUDIO_BANNER", "1")
"#;

/// The SGR sequence that ends a color.
const RESET_SGR: &str = "\u{1b}[0m";

/// The SGR sequence for a 24-bit foreground color.
fn sgr(c: Rgb) -> String {
    format!("\u{1b}[38;2;{};{};{}m", c.r, c.g, c.b)
}

/// A Lua table of strings, each written by `lua_str`: `{ "a", "b" }`.
fn lua_list(items: &[&str]) -> String {
    let quoted: Vec<String> = items.iter().map(|item| lua_str(item)).collect();
    format!("{{ {} }}", quoted.join(", "))
}

/// The Lua that defines the banner variables `V.user()`, `V.host()`, `V.cwd()`, `V.date()`
/// and `V.time()`. One block serves both languages: only the names of the days and months,
/// the pattern of the date and the era of the year are put in front of it (spec §3.6).
fn vars_lua(lang: Lang) -> String {
    let style = match lang {
        Lang::Th => &DATE_TH,
        Lang::En => &DATE_EN,
    };
    format!(
        "local DAYS = {}\nlocal MONTHS = {}\nlocal DATE_FORMAT = {}\nlocal YEAR_OFFSET = {}\n{VARS_BODY}",
        lua_list(&style.days),
        lua_list(&style.months),
        lua_str(style.pattern),
        style.year_offset,
    )
}

/// The function that gives the icon of the box, chosen when the box is printed and not when
/// the script loads.
fn icon_lua() -> String {
    format!(
        "local function icon()\n  if os.getenv(\"WT_SESSION\") then return {} end\n  return {}\nend\n",
        lua_str(ICON),
        lua_str(ICON_FALLBACK)
    )
}

/// The banner variables and the Lua call that stands for each (spec §3.3). They are lower
/// case and keep their braces; any other `{word}` is text.
const VARS: [(&str, &str); 5] = [
    ("{user}", "V.user()"),
    ("{host}", "V.host()"),
    ("{cwd}", "V.cwd()"),
    ("{date}", "V.date()"),
    ("{time}", "V.time()"),
];

/// The first variable in `text`: the text before it, its Lua call and the text after it.
fn next_variable(text: &str) -> Option<(&str, &'static str, &str)> {
    text.match_indices('{').find_map(|(at, _)| {
        let (before, from) = text.split_at_checked(at)?;
        VARS.iter()
            .find_map(|(name, call)| from.strip_prefix(*name).map(|after| (before, *call, after)))
    })
}

/// A banner template as a Lua expression. Known `{variables}` become calls;
/// everything else stays literal (spec §3.3), written by `lua_str`.
pub(crate) fn template_expr(template: &str) -> String {
    let mut parts: Vec<String> = Vec::new();
    let mut rest = template;
    while let Some((before, call, after)) = next_variable(rest) {
        if !before.is_empty() {
            parts.push(lua_str(before));
        }
        parts.push(call.to_string());
        rest = after;
    }
    if !rest.is_empty() {
        parts.push(lua_str(rest));
    }
    if parts.is_empty() {
        lua_str("")
    } else {
        parts.join(" .. ")
    }
}

/// `init.lua`: runs Oh My Posh by its full path, so nothing depends on PATH, and loads what
/// it prints. `io.popen` hands the command to `cmd /c`, which drops the outermost quotes,
/// so the command is `""<exe>" init cmd --config "<config>" 2>nul"` (spec §5.4, G17). The
/// `2>nul` keeps the error text of cmd (a missing exe) out of every window, because
/// `io.popen` pipes stdout only. The script runs in every cmd window, so it never raises
/// and never prints: a failure is logged. Both paths are written by `lua_str`, which keeps
/// Thai letters, spaces, `\` and `]]` as they are. A path that is not valid Unicode is
/// written with U+FFFD in place of the parts that are not.
pub fn init_lua(omp_exe: &Path, omp_config: &Path) -> String {
    let mut s = String::from(HEADER);
    s.push_str(&format!(
        "local omp = {}\n",
        lua_str(&omp_exe.to_string_lossy())
    ));
    s.push_str(&format!(
        "local config = {}\n",
        lua_str(&omp_config.to_string_lossy())
    ));
    s.push_str(INIT_BODY);
    s
}

/// `banner.lua`: the welcome box of the theme (spec §3.6). Loading it registers one
/// `clink.oninject` callback and prints nothing; the callback prints the box once per
/// session, guarded by the environment variable `CMDSTUDIO_BANNER`. A theme with the banner
/// turned off gets a script that registers nothing, so an older banner is replaced by it.
///
/// The texts of the theme go through `sanitize_text` and then `lua_str`. Import has cleaned
/// them already, but a theme built in code has not been through that, and an escape
/// sequence in the title would otherwise reach the terminal.
pub fn banner_lua(theme: &Theme, lang: Lang) -> String {
    let b = &theme.banner;
    let mut s = String::from(HEADER);
    if !b.enabled {
        s.push_str("-- The banner is turned off in this theme.\n");
        return s;
    }
    s.push_str(&format!(
        "local ACCENT = {}\n",
        lua_str(&sgr(theme.colors.accent))
    ));
    s.push_str(&format!(
        "local MUTED = {}\n",
        lua_str(&sgr(theme.colors.muted))
    ));
    s.push_str(&format!("local RESET = {}\n", lua_str(RESET_SGR)));
    s.push_str(&vars_lua(lang));
    s.push_str(&icon_lua());
    s.push_str("local function build()\n  return {\n");
    s.push_str(&format!(
        "    ACCENT .. icon() .. RESET .. \" \" .. ({}),\n",
        template_expr(&sanitize_text(&b.title))
    ));
    if !b.lines.is_empty() {
        s.push_str("    \"\",\n");
        for line in &b.lines {
            s.push_str(&format!(
                "    MUTED .. \"  \" .. ({}) .. RESET,\n",
                template_expr(&sanitize_text(line))
            ));
        }
    }
    s.push_str("  }\nend\n");
    let tips = b.tips.then_some(match lang {
        Lang::Th => TIPS_TH,
        Lang::En => TIPS_EN,
    });
    s.push_str(&format!(
        "local TIPS = {}\n",
        tips.map_or_else(|| "nil".to_string(), lua_str)
    ));
    s.push_str(PRINT_FN);
    if b.clear_logo {
        s.push_str(CLEAR_LOGO_FN);
    }
    s.push_str(ON_INJECT_HEAD);
    if b.clear_logo {
        s.push_str("  clear_cmd_logo()\n");
    }
    s.push_str("  print_banner()\nend)\n");
    s
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::presets::terracotta;
    use std::path::Path;

    #[test]
    fn templates_become_lua_expressions() {
        assert_eq!(
            template_expr("Welcome back, {user}!"),
            "\"Welcome back, \" .. V.user() .. \"!\""
        );
        assert_eq!(
            template_expr("{date} · {time}"),
            "V.date() .. \" · \" .. V.time()"
        );
        assert_eq!(template_expr("{foo} stays"), "\"{foo} stays\"");
        assert_eq!(template_expr(""), "\"\"");
    }

    #[test]
    fn every_variable_is_a_call_and_only_those_five() {
        // spec §3.3: `{user} {host} {cwd} {date} {time}`, in lower case, braces and all
        for (word, call) in [
            ("user", "V.user()"),
            ("host", "V.host()"),
            ("cwd", "V.cwd()"),
            ("date", "V.date()"),
            ("time", "V.time()"),
        ] {
            assert_eq!(template_expr(&format!("{{{word}}}")), call);
        }
        for literal in [
            "{USER}", "{User}", "{ user }", "{user", "user}", "{}", "{", "}", "{{", "{path}",
            "{user }",
        ] {
            assert_eq!(template_expr(literal), lua_str(literal), "{literal:?}");
        }
    }

    #[test]
    fn variables_and_text_can_touch_each_other() {
        assert_eq!(template_expr("{user}{host}"), "V.user() .. V.host()");
        assert_eq!(
            template_expr("a{cwd}b{time}c"),
            "\"a\" .. V.cwd() .. \"b\" .. V.time() .. \"c\""
        );
        // a brace that opens nothing stays text, and the variable inside the second pair is found
        assert_eq!(template_expr("{{user}}"), "\"{\" .. V.user() .. \"}\"");
        assert_eq!(
            template_expr("{use{user}r}"),
            "\"{use\" .. V.user() .. \"r}\""
        );
        // the text on either side may be Thai or emoji: the cuts fall on character boundaries
        assert_eq!(
            template_expr("ก{user}ข 👋{date}"),
            "\"ก\" .. V.user() .. \"ข 👋\" .. V.date()"
        );
        assert_eq!(template_expr("{ก}"), "\"{ก}\"");
    }

    #[test]
    fn text_between_variables_is_escaped_by_lua_str() {
        // spec §3.7 #4: a quote, a backslash, a long-bracket close and a control character
        // are all text; none of them can end the string
        assert_eq!(template_expr("a\"]]\\"), "\"a\\\"]]\\\\\"");
        assert_eq!(
            template_expr("x\ny{user}\u{1b}[0m"),
            "\"x\\010y\" .. V.user() .. \"\\027[0m\""
        );
    }

    #[test]
    fn init_lua_quotes_paths_and_wraps_the_popen_command() {
        let s = init_lua(
            Path::new(r"C:\Users\ทดสอบ ผู้ใช้\omp.exe"),
            Path::new(r"C:\x\theme.omp.json"),
        );
        assert!(s.contains(r#"local omp = "C:\\Users\\ทดสอบ ผู้ใช้\\omp.exe""#));
        assert!(s.contains(r#"io.popen('"' .. '"' .. omp"#));
        // `2>nul` is inside the outer quotes, which cmd drops: io.popen pipes stdout only, so
        // without it cmd's own error text (a missing exe) would be printed in every window
        assert!(s.contains(
            r#"io.popen('"' .. '"' .. omp .. '" init cmd --config "' .. config .. '" 2>nul' .. '"')"#
        ));
    }

    #[test]
    fn init_lua_embeds_both_paths_only_through_lua_str() {
        // `]]` would close a long string, `\` and `"` would break a short one, and a path
        // is free to hold Thai letters and spaces. tests/banner_lua.rs runs the result.
        let exe = r"C:\Users\ทดสอบ ผู้ใช้\]]\--[[\omp.exe";
        let config = r"D:\a b\x]]\theme.omp.json";
        let s = init_lua(Path::new(exe), Path::new(config));
        assert!(s.contains(&format!("local omp = {}\n", lua_str(exe))));
        assert!(s.contains(&format!("local config = {}\n", lua_str(config))));
        assert!(s.starts_with(HEADER));
    }

    #[test]
    fn disabled_banner_registers_nothing() {
        // Review Focus 4
        let mut t = terracotta();
        t.banner.enabled = false;
        assert!(!banner_lua(&t, Lang::En).contains("oninject"));
    }
}
