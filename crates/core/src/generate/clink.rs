//! The Clink settings file for CMD Studio's private profile (spec §5.4).
use std::path::Path;

/// The text of `clink_settings`: the logo off, the transient prompt as the theme wants it,
/// `scripts_dir` as the folder Clink loads Lua scripts from, and no self-update (G16: the
/// runtime is ours, and Clink must not replace it).
///
/// `clink.path` does not add a folder to the ones Clink reads. It takes their place: with it
/// set, Clink loads no script from the folder of its program or from the profile folder
/// (checked on 1.9.34, and Clink's own help for the setting says the same). The Lua API that
/// is built into Clink is there as always. The setting is a list delimited by semicolons, so
/// `scripts_dir` must not contain one.
///
/// This is Clink's own `name = value` format and not Lua, so the path is written as it is
/// and `lua_str` does not apply. A path that is not valid Unicode is written with U+FFFD in
/// place of the parts that are not.
pub fn settings(transient: bool, scripts_dir: &Path) -> String {
    format!(
        "# Generated by CMD Studio. Do not edit: changes are overwritten.\n\
         clink.logo = none\n\
         prompt.transient = {}\n\
         clink.path = {}\n\
         clink.autoupdate = off\n",
        if transient { "always" } else { "off" },
        scripts_dir.display()
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::Path;

    #[test]
    fn writes_the_four_settings() {
        let s = settings(true, Path::new(r"C:\Data\generated"));
        assert!(s.contains("\nclink.logo = none\n"));
        assert!(s.contains("\nprompt.transient = always\n"));
        assert!(s.contains("\nclink.path = C:\\Data\\generated\n"));
        assert!(s.contains("\nclink.autoupdate = off\n"));
        assert!(settings(false, Path::new("x")).contains("\nprompt.transient = off\n"));
    }

    #[test]
    fn the_file_holds_these_settings_and_nothing_else() {
        // A setting that is not listed here would be one nobody decided on (spec §5.4).
        assert_eq!(
            settings(true, Path::new(r"C:\Data\generated")),
            "# Generated by CMD Studio. Do not edit: changes are overwritten.\n\
             clink.logo = none\n\
             prompt.transient = always\n\
             clink.path = C:\\Data\\generated\n\
             clink.autoupdate = off\n"
        );
        assert_eq!(
            settings(false, Path::new(r"C:\Data\generated")),
            "# Generated by CMD Studio. Do not edit: changes are overwritten.\n\
             clink.logo = none\n\
             prompt.transient = off\n\
             clink.path = C:\\Data\\generated\n\
             clink.autoupdate = off\n"
        );
    }

    #[test]
    fn a_folder_with_thai_letters_and_spaces_is_written_as_it_is() {
        // The profile may sit under a Thai user name (G19); the settings file is UTF-8 text,
        // not Lua, so the path is not escaped.
        let s = settings(true, Path::new(r"C:\Users\ทดสอบ ผู้ใช้\generated"));
        assert!(s.contains("\nclink.path = C:\\Users\\ทดสอบ ผู้ใช้\\generated\n"));
    }
}
